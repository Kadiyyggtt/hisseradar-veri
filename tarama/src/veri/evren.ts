const TURKCE_HARF = /[ÇĞİÖŞÜçğıöşü]/;
const BUYUK = (s: string) => s === s.toLocaleUpperCase('tr-TR') && /[A-ZÇĞİÖŞÜ]/.test(s);
const basHarfBuyuk = (s: string) => s.charAt(0).toLocaleUpperCase('tr-TR') + s.slice(1);

/**
 * Sözlükte olmayan sembol için kaynak adını düzelt. BIST: şirket türü ekleri ("AS", "Anonim
 * Şirketi") atılır, "Gayrimenkul Yatırım Ortaklığı" GYO olur, tamamı büyük harfli ad Türkçe
 * kuralla küçültülür (Türkçe harfli sözcükte I→ı, ASCII sözcükte I→i), Türkçe harfi düşmüş
 * bilinen sözcükler düzelir, "Ve" küçülür. ABD: "Inc", "Corp", "Co", "Plc", "ADR" atılır.
 * Sonuç en çok AD_EN_COK harf, sözcük ortasından kesilmez.
 */
export function adDuzelt(ham: string, piyasa: 'BIST' | 'ABD'): string {
  let s = ` ${ham.replace(/\s+/g, ' ').trim()} `;
  if (piyasa === 'ABD') {
    s = s.replace(/^ The /, ' ');
    let once = '';
    while (once !== s) {
      once = s;
      s = s.replace(/[\s,]+(Inc\.?|Incorporated|Corp\.?|Corporation|Co\.?|Company|Plc|PLC|plc|Ltd\.?|Limited|Sponsored ADR|ADR|Class [A-C]|Common Stock)\s*$/, ' ');
    }
  } else {
    s = s.replace(/\s(GAYR[Iİ]MENKUL|Gayr[iı]menkul)\s(YATIR[Iİ]M|Yat[iı]r[iı]m)\s(ORTAKL[Iİ][GĞ][Iİ]|Ortakl[iı][gğ][iı])(?=\s)/g, ' GYO');
    let once = '';
    while (once !== s) {
      once = s;
      s = s.replace(/\s(A\.?\s?[SŞ]\.?|T\.A\.[SŞ]\.|A\.?O\.?|SA|as|ANON[Iİ]M\s(S|Ş)[Iİ]RKET[Iİ]|Anonim\s(S|Ş)irketi|ANON[Iİ]M\sORTAKL[Iİ][GĞ][Iİ]|Anonim\sOrtakl[iı][gğ][iı])\s*$/, ' ');
    }
    s = s.replace(/\s(SANAY[Iİ]\sVE\sT[Iİ]CARET|Sanayi\s[Vv]e\sTicaret)(?=\s)/g, ' ');
    s = s
      .trim()
      .split(' ')
      .map((w, i) => {
        if (i > 0 && /^(ve|Ve|VE)$/.test(w)) return 've';
        // Kısa büyük harfli sözcük kısaltmadır (TR, DMR, GYO): olduğu gibi kalır.
        if (BUYUK(w) && w.replace(/[^A-Za-zÇĞİÖŞÜçğıöşü]/g, '').length <= 3) return w;
        if (!BUYUK(w)) {
          // Karışık harfli ad (CarrefourSA, "Gida" gibi): yalnız bilinen sözcük düzelir, iç büyük harf korunur.
          const d = ASCII_TURKCE[w.toLowerCase()];
          return d ? (/^[A-ZÇĞİÖŞÜ]/.test(w) ? basHarfBuyuk(d) : d) : w;
        }
        const kucuk = TURKCE_HARF.test(w) ? w.toLocaleLowerCase('tr-TR') : w.toLowerCase();
        return basHarfBuyuk(ASCII_TURKCE[kucuk] ?? kucuk);
      })
      .join(' ');
  }
  s = s.replace(/\s{2,}/g, ' ').trim();
  if (s.length > AD_EN_COK) s = s.slice(0, AD_EN_COK + 1).replace(/\s+\S*$/, '');
  s = s.replace(/[\s,&-]+$/, '').replace(/\s(ve|&)$/, '').trim();
  return s.length >= 2 ? s : ham.trim().slice(0, AD_EN_COK);
}

/** Gösterilecek ad: sözlük, yoksa düzeltilmiş kaynak adı. */
export function hisseAdi(kod: string, piyasa: 'BIST' | 'ABD', kaynakAdi: string): string {
  const sozluk = piyasa === 'BIST' ? TURKCE_AD[kod] : ABD_AD[kod];
  return sozluk ?? adDuzelt(kaynakAdi, piyasa);
}
